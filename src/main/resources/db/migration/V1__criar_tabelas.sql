-- =====================================================================
-- V1: esquema inicial do Sistema de Coleta Seletiva
-- Baseado no dicionário de dados da Etapa 1.
-- Enums são armazenados como VARCHAR com CHECK (JPA: @Enumerated(STRING)).
-- Sem exclusão em cascata: registros são inativados, não apagados (RN03).
-- =====================================================================

-- ---------------------------------------------------------------------
-- MORADOR
-- ---------------------------------------------------------------------
CREATE TABLE morador (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    email     VARCHAR(160) NOT NULL,
    telefone  VARCHAR(20),
    ativo     BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uk_morador_email ON morador (lower(email));

-- ---------------------------------------------------------------------
-- ENDERECO (do morador)
-- ---------------------------------------------------------------------
CREATE TABLE endereco (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    morador_id  BIGINT NOT NULL REFERENCES morador (id),
    logradouro  VARCHAR(160) NOT NULL,
    numero      VARCHAR(10),
    sem_numero  BOOLEAN NOT NULL DEFAULT FALSE,
    bairro      VARCHAR(80) NOT NULL,
    municipio   VARCHAR(80) NOT NULL,
    uf          VARCHAR(2) NOT NULL,
    cep         VARCHAR(8) NOT NULL,
    complemento VARCHAR(80),
    CONSTRAINT ck_endereco_numero CHECK (
        (sem_numero AND numero IS NULL) OR (NOT sem_numero AND numero IS NOT NULL)),
    CONSTRAINT ck_endereco_uf  CHECK (uf ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_endereco_cep CHECK (cep ~ '^[0-9]{8}$')
);
CREATE INDEX ix_endereco_morador ON endereco (morador_id);

-- ---------------------------------------------------------------------
-- MATERIAL
-- ---------------------------------------------------------------------
CREATE TABLE material (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(80) NOT NULL,
    descricao           TEXT,
    unidade_medida      VARCHAR(10) NOT NULL,
    orientacao_preparo  TEXT,
    ativo               BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_material_unidade CHECK (unidade_medida IN ('KG', 'LITRO', 'UNIDADE'))
);
CREATE UNIQUE INDEX uk_material_nome ON material (lower(nome));

-- ---------------------------------------------------------------------
-- PONTO_COLETA (endereço embutido)
-- ---------------------------------------------------------------------
CREATE TABLE ponto_coleta (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                    VARCHAR(120) NOT NULL,
    logradouro              VARCHAR(160) NOT NULL,
    numero                  VARCHAR(10) NOT NULL,
    bairro                  VARCHAR(80) NOT NULL,
    municipio               VARCHAR(80) NOT NULL,
    uf                      VARCHAR(2) NOT NULL,
    cep                     VARCHAR(8) NOT NULL,
    contato                 VARCHAR(80),
    horarios                VARCHAR(200),
    ativo                   BOOLEAN NOT NULL DEFAULT TRUE,
    recolhimento_domiciliar BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_ponto_uf  CHECK (uf ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_ponto_cep CHECK (cep ~ '^[0-9]{8}$')
);
CREATE INDEX ix_ponto_localizacao ON ponto_coleta (ativo, municipio, bairro);
CREATE INDEX ix_ponto_nome        ON ponto_coleta (lower(nome));

-- ---------------------------------------------------------------------
-- MATERIAL_ACEITO (ponto x material)
-- ---------------------------------------------------------------------
CREATE TABLE material_aceito (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id                BIGINT NOT NULL REFERENCES ponto_coleta (id),
    material_id             BIGINT NOT NULL REFERENCES material (id),
    observacoes             VARCHAR(200),
    limite_por_solicitacao  NUMERIC(12,3),
    CONSTRAINT uk_material_aceito UNIQUE (ponto_id, material_id),
    CONSTRAINT ck_material_aceito_limite CHECK (limite_por_solicitacao IS NULL OR limite_por_solicitacao > 0)
);
CREATE INDEX ix_material_aceito_material ON material_aceito (material_id);

-- ---------------------------------------------------------------------
-- OPERADOR e OPERADOR_PONTO
-- ---------------------------------------------------------------------
CREATE TABLE operador (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(120) NOT NULL,
    email  VARCHAR(160) NOT NULL,
    ativo  BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uk_operador_email ON operador (lower(email));

CREATE TABLE operador_ponto (
    operador_id  BIGINT NOT NULL REFERENCES operador (id),
    ponto_id     BIGINT NOT NULL REFERENCES ponto_coleta (id),
    PRIMARY KEY (operador_id, ponto_id)
);
CREATE INDEX ix_operador_ponto_ponto ON operador_ponto (ponto_id);

-- ---------------------------------------------------------------------
-- SOLICITACAO
-- ---------------------------------------------------------------------
CREATE SEQUENCE protocolo_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE solicitacao (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo             VARCHAR(20) NOT NULL,
    morador_id            BIGINT NOT NULL REFERENCES morador (id),
    ponto_id              BIGINT NOT NULL REFERENCES ponto_coleta (id),
    -- cópia do endereço de atendimento no momento da solicitação (RN04)
    endereco_logradouro   VARCHAR(160) NOT NULL,
    endereco_numero       VARCHAR(10),
    endereco_bairro       VARCHAR(80) NOT NULL,
    endereco_municipio    VARCHAR(80) NOT NULL,
    endereco_uf           VARCHAR(2) NOT NULL,
    endereco_cep          VARCHAR(8) NOT NULL,
    endereco_complemento  VARCHAR(80),
    situacao              VARCHAR(20) NOT NULL,
    data_criacao          TIMESTAMPTZ NOT NULL DEFAULT now(),
    data_agendamento      TIMESTAMPTZ,
    data_conclusao        TIMESTAMPTZ,
    observacoes           TEXT,
    versao                BIGINT NOT NULL DEFAULT 0,   -- controle de concorrência (RN06)
    CONSTRAINT uk_solicitacao_protocolo UNIQUE (protocolo),
    CONSTRAINT ck_solicitacao_situacao CHECK (situacao IN
        ('SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO', 'CONCLUIDA', 'RECUSADA', 'CANCELADA'))
);
CREATE INDEX ix_solicitacao_ponto_situacao ON solicitacao (ponto_id, situacao, data_criacao);
CREATE INDEX ix_solicitacao_morador        ON solicitacao (morador_id, data_criacao);

-- ---------------------------------------------------------------------
-- ITEM_SOLICITACAO
-- ---------------------------------------------------------------------
CREATE TABLE item_solicitacao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id       BIGINT NOT NULL REFERENCES solicitacao (id),
    material_id          BIGINT NOT NULL REFERENCES material (id),
    unidade              VARCHAR(10) NOT NULL,           -- cópia da unidade do material (RN04)
    quantidade_estimada  NUMERIC(12,3) NOT NULL,
    quantidade_efetiva   NUMERIC(12,3),
    CONSTRAINT uk_item_solicitacao UNIQUE (solicitacao_id, material_id),
    CONSTRAINT ck_item_unidade   CHECK (unidade IN ('KG', 'LITRO', 'UNIDADE')),
    CONSTRAINT ck_item_estimada  CHECK (quantidade_estimada > 0),
    CONSTRAINT ck_item_efetiva   CHECK (quantidade_efetiva IS NULL OR quantidade_efetiva >= 0)
);
CREATE INDEX ix_item_material ON item_solicitacao (material_id);

-- ---------------------------------------------------------------------
-- HISTORICO
-- ---------------------------------------------------------------------
CREATE TABLE historico (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id      BIGINT NOT NULL REFERENCES solicitacao (id),
    situacao_anterior   VARCHAR(20),                     -- nula no registro de criação
    situacao_nova       VARCHAR(20) NOT NULL,
    data_hora           TIMESTAMPTZ NOT NULL DEFAULT now(),
    responsavel_tipo    VARCHAR(15) NOT NULL,
    responsavel_id      BIGINT,
    motivo              TEXT,
    numero_tentativa    INTEGER,
    detalhes_tentativa  TEXT,
    CONSTRAINT ck_historico_responsavel CHECK (responsavel_tipo IN ('MORADOR', 'OPERADOR', 'ADMINISTRADOR')),
    CONSTRAINT ck_historico_anterior CHECK (situacao_anterior IS NULL OR situacao_anterior IN
        ('SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO', 'CONCLUIDA', 'RECUSADA', 'CANCELADA')),
    CONSTRAINT ck_historico_nova CHECK (situacao_nova IN
        ('SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO', 'CONCLUIDA', 'RECUSADA', 'CANCELADA'))
);
CREATE INDEX ix_historico_solicitacao ON historico (solicitacao_id, data_hora);
